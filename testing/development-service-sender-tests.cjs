const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const {createRuntime} = require('./performance-fixtures.cjs');
const source = path.resolve(__dirname, '../Code.js');
const runtime = createRuntime(source, 0);
vm.runInContext(fs.readFileSync(path.resolve(__dirname, '../DevelopmentSender.js'), 'utf8'), runtime.api);
runtime.setActor('andy.clifton@claremontschool.co.uk');
runtime.sheets.Config.rows[2][1] = 'service.orders@claremontschool.co.uk';
